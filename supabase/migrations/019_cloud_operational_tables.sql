-- Cloud tables used by the workforce SOS, warehouse, and commercial read APIs.
-- New installations and existing projects can run this migration safely.
BEGIN;

CREATE TABLE IF NOT EXISTS public.sos_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES public.companies(id),
  employee_id INTEGER REFERENCES public.employees(id),
  agent_id INTEGER REFERENCES public.users(id),
  message TEXT NOT NULL DEFAULT 'Emergency Assistance Required',
  latitude NUMERIC(10,7), longitude NUMERIC(10,7), accuracy NUMERIC,
  address TEXT, battery_level INTEGER DEFAULT 100,
  status TEXT NOT NULL DEFAULT 'active',
  acknowledged_by INTEGER REFERENCES public.users(id), acknowledged_at TIMESTAMPTZ,
  resolved_by INTEGER REFERENCES public.users(id), resolved_at TIMESTAMPTZ,
  resolution_notes TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS nexfeild_sos_events_queue ON public.sos_events(company_id,status,created_at DESC);

CREATE TABLE IF NOT EXISTS public.warehouse_managers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES public.companies(id),
  user_id INTEGER NOT NULL REFERENCES public.users(id),
  active BOOLEAN NOT NULL DEFAULT true, assigned_by INTEGER REFERENCES public.users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(company_id,user_id)
);
CREATE TABLE IF NOT EXISTS public.warehouse_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES public.companies(id),
  request_number TEXT NOT NULL,
  requester_user_id INTEGER NOT NULL REFERENCES public.users(id),
  purpose TEXT, notes TEXT, use_location TEXT,
  needed_by DATE, due_date DATE,
  status TEXT NOT NULL DEFAULT 'PENDING',
  decision_by INTEGER REFERENCES public.users(id), decision_at TIMESTAMPTZ, decision_note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(company_id,request_number)
);
CREATE TABLE IF NOT EXISTS public.warehouse_request_lines (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES public.companies(id),
  request_id INTEGER NOT NULL REFERENCES public.warehouse_requests(id),
  product_id INTEGER NOT NULL REFERENCES public.products(id),
  requested_quantity INTEGER NOT NULL DEFAULT 0,
  approved_quantity INTEGER NOT NULL DEFAULT 0,
  issued_quantity INTEGER NOT NULL DEFAULT 0,
  returned_quantity INTEGER NOT NULL DEFAULT 0,
  is_returnable BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(request_id,product_id)
);
CREATE TABLE IF NOT EXISTS public.warehouse_returns (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES public.companies(id),
  request_id INTEGER NOT NULL REFERENCES public.warehouse_requests(id),
  line_id INTEGER NOT NULL REFERENCES public.warehouse_request_lines(id),
  quantity INTEGER NOT NULL DEFAULT 0,
  condition TEXT, place TEXT, space TEXT, notes TEXT,
  status TEXT NOT NULL DEFAULT 'PENDING', submitted_by INTEGER REFERENCES public.users(id),
  received_by INTEGER REFERENCES public.users(id), received_at TIMESTAMPTZ, receipt_note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.warehouse_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES public.companies(id),
  request_id INTEGER NOT NULL REFERENCES public.warehouse_requests(id),
  actor_id INTEGER REFERENCES public.users(id), action TEXT NOT NULL,
  details JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.warehouse_notices (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES public.companies(id),
  request_id INTEGER REFERENCES public.warehouse_requests(id),
  user_id INTEGER NOT NULL REFERENCES public.users(id),
  title TEXT NOT NULL, body TEXT,
  read_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.warehouse_operations (
  id TEXT PRIMARY KEY, company_id INTEGER NOT NULL REFERENCES public.companies(id),
  user_id INTEGER NOT NULL REFERENCES public.users(id),
  action TEXT NOT NULL, payload_hash TEXT NOT NULL, result JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.warehouse_stock_locations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES public.companies(id),
  product_id INTEGER NOT NULL REFERENCES public.products(id),
  place TEXT NOT NULL, space TEXT NOT NULL, condition TEXT,
  stock_state TEXT NOT NULL DEFAULT 'AVAILABLE', quantity INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS nexfeild_warehouse_requests_queue ON public.warehouse_requests(company_id,status,created_at DESC);
CREATE INDEX IF NOT EXISTS nexfeild_warehouse_notices_inbox ON public.warehouse_notices(company_id,user_id,created_at DESC);
CREATE INDEX IF NOT EXISTS nexfeild_warehouse_stock_product ON public.warehouse_stock_locations(company_id,product_id);

CREATE TABLE IF NOT EXISTS public.commercial_records (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES public.companies(id),
  kind TEXT NOT NULL, record_key TEXT NOT NULL,
  owner_id INTEGER REFERENCES public.users(id), customer_id INTEGER REFERENCES public.customers(id),
  status TEXT NOT NULL DEFAULT 'active', version INTEGER NOT NULL DEFAULT 1,
  payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(company_id,record_key)
);
CREATE TABLE IF NOT EXISTS public.commercial_operations (
  id TEXT PRIMARY KEY, company_id INTEGER NOT NULL REFERENCES public.companies(id),
  actor_key TEXT NOT NULL, action TEXT NOT NULL, fingerprint TEXT NOT NULL,
  result JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.commercial_balances (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES public.companies(id),
  account_id INTEGER NOT NULL REFERENCES public.commercial_records(id),
  product_id INTEGER NOT NULL REFERENCES public.products(id),
  quantity INTEGER NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(company_id,account_id,product_id)
);
CREATE TABLE IF NOT EXISTS public.commercial_stock_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES public.companies(id),
  account_id INTEGER NOT NULL REFERENCES public.commercial_records(id),
  product_id INTEGER NOT NULL REFERENCES public.products(id),
  actor_id INTEGER REFERENCES public.users(id),
  movement TEXT NOT NULL, quantity INTEGER NOT NULL, balance_after INTEGER NOT NULL,
  reference TEXT, note TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.commercial_portal_accounts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES public.companies(id),
  customer_id INTEGER NOT NULL REFERENCES public.customers(id),
  email TEXT NOT NULL, password_hash TEXT NOT NULL,
  password_version INTEGER NOT NULL DEFAULT 1,
  requires_password_change BOOLEAN NOT NULL DEFAULT true,
  status TEXT NOT NULL DEFAULT 'active', created_by INTEGER REFERENCES public.users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(company_id,email)
);
CREATE TABLE IF NOT EXISTS public.commercial_campaign_deliveries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES public.companies(id),
  campaign_id INTEGER NOT NULL REFERENCES public.commercial_records(id),
  customer_id INTEGER REFERENCES public.customers(id),
  channel TEXT NOT NULL, provider_id TEXT, status TEXT NOT NULL DEFAULT 'pending',
  note TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS nexfeild_commercial_records_lookup ON public.commercial_records(company_id,kind,status);
CREATE INDEX IF NOT EXISTS nexfeild_commercial_deliveries_lookup ON public.commercial_campaign_deliveries(company_id,campaign_id,created_at DESC);

DO $$ DECLARE table_name TEXT; BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'sos_events','warehouse_managers','warehouse_requests','warehouse_request_lines',
    'warehouse_returns','warehouse_events','warehouse_notices','warehouse_operations',
    'warehouse_stock_locations','commercial_records','commercial_operations',
    'commercial_balances','commercial_stock_events','commercial_portal_accounts',
    'commercial_campaign_deliveries'
  ] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',table_name);
    EXECUTE format('REVOKE ALL ON public.%I FROM anon, authenticated',table_name);
    EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON public.%I TO service_role',table_name);
  END LOOP;
END $$;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
NOTIFY pgrst, 'reload schema';
COMMIT;
